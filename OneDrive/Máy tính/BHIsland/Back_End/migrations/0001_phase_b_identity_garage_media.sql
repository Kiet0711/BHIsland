CREATE TABLE media_assets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL REFERENCES users(id),
  storage_key text NOT NULL UNIQUE,
  mime_type text NOT NULL
    CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp', 'image/avif')),
  byte_size bigint NOT NULL CHECK (byte_size BETWEEN 1 AND 15728640),
  width integer CHECK (width IS NULL OR width BETWEEN 1 AND 12000),
  height integer CHECK (height IS NULL OR height BETWEEN 1 AND 12000),
  checksum text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'ready', 'rejected', 'deleted')),
  alt_text varchar(300),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT media_assets_dimensions_pair_check
    CHECK ((width IS NULL AND height IS NULL) OR (width IS NOT NULL AND height IS NOT NULL)),
  CONSTRAINT media_assets_pixel_limit_check
    CHECK (width IS NULL OR height IS NULL OR width::bigint * height::bigint <= 40000000)
);
CREATE INDEX media_assets_owner_created_idx
  ON media_assets(owner_id, created_at DESC);
CREATE INDEX media_assets_pending_idx
  ON media_assets(created_at) WHERE status IN ('pending', 'processing');

ALTER TABLE users
  ADD CONSTRAINT users_avatar_media_fk
  FOREIGN KEY (avatar_media_id) REFERENCES media_assets(id) ON DELETE SET NULL;

CREATE TABLE vehicles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL REFERENCES users(id),
  vehicle_type_id smallint NOT NULL REFERENCES vehicle_types(id),
  title varchar(120) NOT NULL,
  make varchar(80),
  model varchar(100),
  model_year integer CHECK (model_year IS NULL OR model_year BETWEEN 1886 AND 2100),
  description varchar(2000),
  cover_media_id uuid REFERENCES media_assets(id) ON DELETE SET NULL,
  attributes jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(attributes) = 'object'),
  visibility text NOT NULL DEFAULT 'public'
    CHECK (visibility IN ('public', 'followers', 'private')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT vehicles_title_check CHECK (length(btrim(title)) BETWEEN 1 AND 120)
);
CREATE INDEX vehicles_owner_created_idx
  ON vehicles(owner_id, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX vehicles_type_make_model_idx
  ON vehicles(vehicle_type_id, make, model);

