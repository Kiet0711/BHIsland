-- GIsland Phase B baseline: identity, profiles, vehicle taxonomy/garage, media.
-- Apply only through the migration runner after the PostgreSQL version and runner
-- are selected. This file is immutable after it has been applied to a shared DB.

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email_normalized text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  username text NOT NULL UNIQUE,
  display_name varchar(80) NOT NULL,
  bio varchar(500),
  avatar_media_id uuid,
  role text NOT NULL DEFAULT 'member'
    CHECK (role IN ('member', 'moderator', 'admin')),
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'active', 'suspended', 'deleted')),
  email_verified_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT users_email_normalized_check
    CHECK (email_normalized = lower(btrim(email_normalized))),
  CONSTRAINT users_username_check
    CHECK (username ~ '^[a-z0-9_]{3,30}$'),
  CONSTRAINT users_display_name_check
    CHECK (length(btrim(display_name)) BETWEEN 1 AND 80),
  CONSTRAINT users_password_hash_check
    CHECK (length(password_hash) > 0)
);

CREATE TABLE user_profiles (
  user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  location_text varchar(120),
  website_url text,
  privacy text NOT NULL DEFAULT 'public'
    CHECK (privacy IN ('public', 'private')),
  preferences jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(preferences) = 'object')
);

-- Store only a hash of the random bearer token; never store the cookie value.
CREATE TABLE user_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash bytea NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  last_seen_at timestamptz,
  CONSTRAINT user_sessions_token_hash_check CHECK (octet_length(token_hash) = 32),
  CONSTRAINT user_sessions_expiry_check CHECK (expires_at > created_at)
);
CREATE INDEX user_sessions_user_active_idx
  ON user_sessions(user_id, expires_at DESC) WHERE revoked_at IS NULL;

-- Shared one-time token table for email verification and password reset.
CREATE TABLE auth_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  purpose text NOT NULL CHECK (purpose IN ('email_verification', 'password_reset')),
  token_hash bytea NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  CONSTRAINT auth_tokens_hash_check CHECK (octet_length(token_hash) = 32),
  CONSTRAINT auth_tokens_expiry_check CHECK (expires_at > created_at)
);
CREATE INDEX auth_tokens_user_purpose_idx
  ON auth_tokens(user_id, purpose, expires_at DESC) WHERE consumed_at IS NULL;

CREATE TABLE vehicle_types (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name varchar(80) NOT NULL,
  active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  CONSTRAINT vehicle_types_slug_check CHECK (slug ~ '^[a-z0-9-]{1,40}$')
);

